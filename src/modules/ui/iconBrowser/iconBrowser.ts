import { LightningElement } from 'lwc';
import { ICONS, UNMAPPED, MAPPED_COUNT } from 'data/icons';

interface Icon {
    slug: string;
    name: string;
    iconName: string;
    figmaNode: string | null;
    notes: string[];
    drawnFor: string[];
}

interface Unmapped {
    name: string;
    usedIn: string[];
}

const ALL = ICONS as Icon[];
const OURS = (UNMAPPED as { ours: Unmapped[]; base: Unmapped[] }).ours;
const BASE = (UNMAPPED as { ours: Unmapped[]; base: Unmapped[] }).base;

const FIGMA_FILE = 'https://www.figma.com/design/BIYTe4aj1tFOEPvEWoBjgb/SEP---Foundations-UI-Library';

const PLACEHOLDER_COLUMNS = [
    { label: 'Salesforce name', fieldName: 'name', initialWidth: 220 },
    { label: 'Used in', fieldName: 'usedInLabel', wrapText: true }
];

const tableRows = (rows: Unmapped[]) =>
    rows.map((r) => ({ ...r, usedInLabel: r.usedIn.join(', ') }));

/**
 * The SEP icon set, and which Salesforce icon names draw each icon.
 *
 * Every `lightning-*` icon on the site draws from this set, not Salesforce's:
 * the ten `lightning/iconSvgTemplates<Category>` libraries resolve to the
 * generated `sep/icons` module (rules-architecture.md § Icons). Markup keeps
 * Salesforce names; `src/icons/icon-map.json` decides the SEP icon each draws,
 * and anything unmapped draws a placeholder.
 *
 * Each tile is a real `lightning-icon` asking for `utility:sep_<slug>`, so the
 * page renders through the same library every screen uses -- a broken import
 * shows here as a wall of placeholders.
 *
 * Generated by `npm run icons` (data/icons); nothing here is hand-maintained.
 */
export default class IconBrowser extends LightningElement {
    static renderMode: 'light' | 'shadow' = 'light';

    query = '';

    placeholderColumns = PLACEHOLDER_COLUMNS;
    oursRows = tableRows(OURS);
    baseRows = tableRows(BASE);
    figmaUrl = `${FIGMA_FILE}?node-id=11-383`;

    get summary(): string {
        const unused = ALL.filter((i) => !i.drawnFor.length).length;
        return (
            `${ALL.length} icons, ${MAPPED_COUNT} Salesforce names mapped to them. ` +
            `${unused} icons have no Salesforce name and are reached only by their own ` +
            `utility:sep_… name. ${OURS.length} names our code uses draw the placeholder.`
        );
    }

    get icons() {
        const term = this.query.trim().toLowerCase();
        return ALL.filter(
            (i) =>
                !term ||
                i.name.toLowerCase().includes(term) ||
                i.iconName.includes(term) ||
                i.drawnFor.some((n) => n.includes(term))
        ).map((i) => ({
            ...i,
            nameParts: i.iconName.split(/(?<=_)/).map((text, n) => ({ key: `${i.slug}-${n}`, text })),
            hasDrawnFor: i.drawnFor.length > 0,
            drawnForLabel: i.drawnFor.join(', '),
            hasNotes: i.notes.length > 0,
            notesLabel: i.notes.join(' '),
            figmaUrl: i.figmaNode ? `${FIGMA_FILE}?node-id=${i.figmaNode.replace(':', '-')}` : null
        }));
    }

    get noMatches(): boolean {
        return this.icons.length === 0;
    }

    get hasOurs(): boolean {
        return this.oursRows.length > 0;
    }

    get hasBase(): boolean {
        return this.baseRows.length > 0;
    }

    handleSearch(event: Event): void {
        this.query = (event.target as HTMLInputElement).value ?? '';
    }
}
