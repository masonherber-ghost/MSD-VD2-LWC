import { LightningElement, api } from 'lwc';
import {
    GLOBAL_FAMILIES,
    COMPONENT_HOOKS,
    PROJECT_TOKENS,
    PRIVATE_HOOKS
} from 'data/tokens';

interface Token {
    name: string;
    value?: string;
}

interface Family {
    family: string;
    preview: string;
    tokens: Token[];
}

interface Row extends Token {
    key: string;
    /** Set on the one preview shape this row uses, so the template can pick. */
    isSwatch: boolean;
    isBar: boolean;
    isRadius: boolean;
    isShadow: boolean;
    isText: boolean;
    style: string;
    computed: string;
}

const FAMILIES = GLOBAL_FAMILIES as Family[];

/**
 * Browses the design tokens that are actually installed.
 *
 * The data is generated by `scripts/build-tokens.mjs` from the shipped
 * stylesheet, so it cannot drift from the package the way a hand-written list
 * would. Every preview paints with `var(--token)` rather than the parsed
 * literal, which means what you see is what the browser resolves — including
 * tokens whose value is a chain of other tokens.
 */
export default class TokenBrowser extends LightningElement {
    static renderMode: 'light' | 'shadow' = 'light';

    /**
     * Which half to render: `tokens` (ours plus the SLDS global scale) or
     * `hooks` (what may be set on a component, and what may not). They are two
     * different questions — "what values exist" and "what can I change" — so
     * they get a tab each, while the generated data stays read in one place.
     */
    @api section: 'tokens' | 'hooks' = 'tokens';

    family = FAMILIES[0]?.family ?? 'color';
    query = '';
    hookComponent = (COMPONENT_HOOKS as { component: string }[])[0]?.component ?? '';

    projectTokens = (PROJECT_TOKENS as { name: string; value: string; steps: string[] }[]).map(
        (t) => ({
            ...t,
            key: t.name,
            hasSteps: t.steps.length > 0,
            stepList: t.steps.map((s, i) => ({ key: `${t.name}-${i}`, value: s }))
        })
    );

    privateCount = (PRIVATE_HOOKS as Token[]).length;

    renderedCallback(): void {
        // Resolve each token against the live stylesheet. Only the browser can
        // do this: many values are var() chains several levels deep.
        const root = getComputedStyle(document.documentElement);
        for (const el of this.querySelectorAll('[data-token]')) {
            const name = (el as HTMLElement).dataset.token as string;
            const resolved = root.getPropertyValue(name).trim();
            const target = el.querySelector('[data-computed]');
            if (target && target.textContent !== resolved) {
                target.textContent = resolved || '—';
            }
        }
    }

    get isTokens(): boolean {
        return this.section === 'tokens';
    }

    get isHooks(): boolean {
        return this.section === 'hooks';
    }

    get familyTabs(): { key: string; label: string; count: number; variant: string }[] {
        return FAMILIES.map((f) => ({
            key: f.family,
            label: f.family,
            count: f.tokens.length,
            variant: f.family === this.family ? 'brand' : 'neutral'
        }));
    }

    get currentFamily(): Family {
        return FAMILIES.find((f) => f.family === this.family) ?? FAMILIES[0];
    }

    get rows(): Row[] {
        const f = this.currentFamily;
        const term = this.query.trim().toLowerCase();
        return f.tokens
            .filter((t) => !term || t.name.toLowerCase().includes(term))
            .map((t) => ({
                ...t,
                key: t.name,
                isSwatch: f.preview === 'swatch',
                isBar: f.preview === 'bar',
                isRadius: f.preview === 'radius',
                isShadow: f.preview === 'shadow',
                isText: f.preview === 'text',
                style: this.styleFor(f.preview, t.name),
                computed: ''
            }));
    }

    private styleFor(preview: string, name: string): string {
        switch (preview) {
            case 'swatch':
                return `background:var(${name})`;
            case 'bar':
                return `width:var(${name})`;
            case 'radius':
                return `border-radius:var(${name})`;
            case 'shadow':
                return `box-shadow:var(${name})`;
            case 'text':
                return `font-size:var(${name})`;
            default:
                return '';
        }
    }

    get rowCount(): string {
        const shown = this.rows.length;
        const total = this.currentFamily.tokens.length;
        return shown === total ? `${total} tokens` : `${shown} of ${total} tokens`;
    }

    get hookTabs(): { key: string; label: string; count: number; variant: string }[] {
        return (COMPONENT_HOOKS as { component: string; tokens: Token[] }[]).map((c) => ({
            key: c.component,
            label: c.component,
            count: c.tokens.length,
            variant: c.component === this.hookComponent ? 'brand' : 'neutral'
        }));
    }

    get hookRows(): { key: string; name: string }[] {
        const c = (COMPONENT_HOOKS as { component: string; tokens: Token[] }[]).find(
            (x) => x.component === this.hookComponent
        );
        return (c?.tokens ?? []).map((t) => ({ key: t.name, name: t.name }));
    }

    handleFamily(event: Event): void {
        this.family = (event.currentTarget as HTMLElement).dataset.value as string;
    }

    handleHookComponent(event: Event): void {
        this.hookComponent = (event.currentTarget as HTMLElement).dataset.value as string;
    }

    handleSearch(event: Event): void {
        this.query = (event.target as HTMLInputElement).value ?? '';
    }
}
