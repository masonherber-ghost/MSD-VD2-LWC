import { LightningElement } from 'lwc';
import { SLDS_VERSION, TYPE_CLASSES, TYPE_SCALE, TYPE_WEIGHTS } from 'data/foundations';

interface TypeClass {
    name: string;
    sizeToken: string;
    size: string;
    px: string;
    weight: string;
    lineHeight: string;
    transform: string;
}

interface ScaleStep {
    name: string;
    value: string;
    px: string;
    aliasOf: string;
    classes: string[];
}

interface Weight {
    name: string;
    value: string;
    classes: string[];
}

const SAMPLE = 'Site Foreperson — Ōwhango';

/**
 * The Foundations tab at /design-system. Typography first: every class in the
 * loaded Cosmos stylesheet that sets type, the whole size scale with the
 * classes that reach each step, and the weights.
 *
 * Generated by `npm run foundations` (`scripts/build-foundations.mjs`) from the
 * installed stylesheet, never hand-maintained — the same rule as every other
 * tab on the page. The samples on the scale and weight rows set the TOKEN
 * through an inline style, so a step with no class can still be seen; the
 * class samples use the class itself.
 *
 * No stylesheet: SLDS cards and tables only.
 */
export default class FoundationsBrowser extends LightningElement {
    static renderMode: 'light' | 'shadow' = 'light';

    version = SLDS_VERSION;
    sample = SAMPLE;

    get summary(): string {
        const scale = TYPE_SCALE as ScaleStep[];
        const reached = scale.filter((s) => s.classes.length).length;
        return (
            `SLDS ${this.version}, Cosmos theme. ${TYPE_CLASSES.length} classes set type; ` +
            `${reached} of the ${scale.length} size steps have one. Every other size, and ` +
            `every weight except two, needs a CSS rule that reads the token.`
        );
    }

    get typeClasses() {
        return (TYPE_CLASSES as TypeClass[]).map((c) => ({
            ...c,
            key: c.name,
            weightLabel: c.weight || 'inherited',
            lineHeightLabel: c.lineHeight || 'inherited',
            caseLabel: c.transform || '—'
        }));
    }

    get scaleSteps() {
        return (TYPE_SCALE as ScaleStep[]).map((s) => ({
            ...s,
            key: s.name,
            hasClass: s.classes.length > 0,
            classLabel: s.classes.join(', '),
            aliasLabel: s.aliasOf ? `alias of ${s.aliasOf}` : '',
            sampleStyle: `font-size: var(${s.name});`,
            cssHint: `font-size: var(${s.name});`
        }));
    }

    get weights() {
        return (TYPE_WEIGHTS as Weight[]).map((w) => ({
            ...w,
            key: w.name,
            hasClass: w.classes.length > 0,
            classLabel: w.classes.join(', '),
            sampleStyle: `font-weight: var(${w.name});`,
            cssHint: `font-weight: var(${w.name});`
        }));
    }
}
