interface AlertExample {
    key: string;
    label: string;
    variant: 'info' | 'warning' | 'error' | 'offline';
    cls: string;
    text: string;
}

/**
 * The Alert blueprint's four styles, rendered through `ui/alert` so the markup
 * has one source. `cls` mirrors the class string that wrapper writes.
 *
 * Note the coverage column for this blueprint says `lightning-alert`: the
 * generator credits it by NAME, but `lightning-alert` is the modal dialog
 * (`LightningAlert.open()`), not this in-page banner. Nothing ships the
 * banner — that is why `ui/alert` exists.
 */
const ALERT_EXAMPLES: Record<string, AlertExample[]> = {
    alert: [
        { key: 'info', label: 'Informational', variant: 'info',
          cls: 'slds-notify slds-notify_alert',
          text: 'Informational: the default alert, with no modifier.' },
        { key: 'warning', label: 'Warning', variant: 'warning',
          cls: 'slds-notify slds-notify_alert slds-alert_warning',
          text: 'Warning: something needs attention.' },
        { key: 'error', label: 'Error', variant: 'error',
          cls: 'slds-notify slds-notify_alert slds-alert_error',
          text: 'Error: something went wrong.' },
        { key: 'offline', label: 'Offline', variant: 'offline',
          cls: 'slds-notify slds-notify_alert slds-alert_offline',
          text: 'Offline: you are not connected.' }
    ]
};

const hasExample = (name: string): boolean => Boolean(EXAMPLES[name] || ALERT_EXAMPLES[name]);

/**
 * Browses the SLDS 2 blueprints that are installed.
 *
 * The blueprints are tier 2 of the lego: the classes you write by hand for a
 * structure no `lightning-*` component covers. They are also the easiest thing
 * on the site to get wrong, because SLDS 2 dropped classes SLDS 1 had and a
 * class that does not exist fails silently -- the markup renders, unstyled.
 *
 * So by default it lists only the blueprints NO shipped component renders --
 * the ones you genuinely have to write by hand. Coverage is computed from the
 * classes the components actually emit, not from their names; see
 * `scripts/build-blueprints.mjs`.
 *
 * Generated by `npm run blueprints` from `dist/components/*`, never
 * hand-maintained -- see `scripts/build-blueprints.mjs`.
 */
export default class BlueprintBrowser extends LightningElement {
    static renderMode: 'light' | 'shadow' = 'light';

    version = SLDS_VERSION;
    query = '';
    /** Off by default: the covered ones are the Components tab's job. */
    showCovered = false;
    usedOnly = false;
    selected = ALL.find((b) => !b.coveredBy.length)?.name ?? ALL[0]?.name ?? '';

    get summary(): string {
        const uncovered = ALL.filter((b) => !b.coveredBy.length).length;
        const used = ALL.filter((b) => b.usedIn.length).length;
        return (
            `${ALL.length} blueprints in SLDS ${this.version}. ` +
            `${uncovered} are not rendered by any shipped component — those are the ` +
            `ones you write by hand, and the only ones listed below. ` +
            `${used} of the ${ALL.length} are used on this site.`
        );
    }

    get matches(): Blueprint[] {
        const term = this.query.trim().toLowerCase();
        return ALL.filter((b) => {
            if (!this.showCovered && b.coveredBy.length && !hasExample(b.name)) return false;
            if (this.usedOnly && !b.usedIn.length) return false;
            if (!term) return true;
            // Match the class names too: "what ships the class I half-remember"
            // is the question this page gets asked most.
            return (
                b.name.toLowerCase().includes(term) ||
                b.classes.some((c) => c.includes(term))
            );
        });
    }

    get navItems(): { name: string; label: string; count: number }[] {
        return this.matches.map((b) => ({
            name: b.name,
            label: b.name,
            count: b.classes.length
        }));
    }

    get matchCount(): string {
        return `${this.matches.length} of ${ALL.length}`;
    }

    /** The selection can be filtered away; fall back rather than blank out. */
    get current(): Blueprint {
        return (
            this.matches.find((b) => b.name === this.selected) ??
            this.matches[0] ??
            ALL[0]
        );
    }

    get selectedName(): string {
        return this.current?.name ?? '';
    }

    get ownClasses(): { key: string; name: string }[] {
        return this.current.classes.map((c) => ({ key: c, name: c }));
    }

    get borrowedClasses(): { key: string; name: string }[] {
        return this.current.borrowed.map((c) => ({ key: c, name: c }));
    }

    get hookList(): { key: string; name: string }[] {
        return this.current.hooks.map((h) => ({ key: h, name: h }));
    }

    get privateList(): { key: string; name: string }[] {
        return this.current.privateHooks.map((h) => ({ key: h, name: h }));
    }

    get usedList(): { key: string; name: string }[] {
        return this.current.usedIn.map((f) => ({ key: f, name: f }));
    }

    get missingList(): { key: string; name: string }[] {
        return this.current.missing.map((c) => ({ key: c, name: c }));
    }

    get examples(): Example[] {
        return EXAMPLES[this.current.name] ?? [];
    }

    get hasExamples(): boolean {
        return this.examples.length > 0;
    }

    get alertExamples(): AlertExample[] {
        return ALERT_EXAMPLES[this.current.name] ?? [];
    }

    get hasAlertExamples(): boolean {
        return this.alertExamples.length > 0;
    }

    get hasBorrowed(): boolean {
        return this.current.borrowed.length > 0;
    }

    get hasHooks(): boolean {
        return this.current.hooks.length > 0;
    }

    get hasPrivate(): boolean {
        return this.current.privateHooks.length > 0;
    }

    get isUsed(): boolean {
        return this.current.usedIn.length > 0;
    }

    get hasMissing(): boolean {
        return this.current.missing.length > 0;
    }

    get coveredList(): { key: string; name: string }[] {
        return this.current.coveredBy.map((t) => ({ key: t, name: t }));
    }

    get isCovered(): boolean {
        return this.current.coveredBy.length > 0;
    }

    get sizeLabel(): string {
        return `${Math.round(this.current.bytes / 1024)} KB of CSS`;
    }

    handleSearch(event: Event): void {
        this.query = (event.target as HTMLInputElement).value ?? '';
    }

    handleShowCovered(event: Event): void {
        this.showCovered = (event.target as HTMLInputElement).checked;
    }

    handleUsedOnly(event: Event): void {
        this.usedOnly = (event.target as HTMLInputElement).checked;
    }

    handleSelect(event: CustomEvent): void {
        this.selected = (event.detail as { name: string }).name;
    }
}
