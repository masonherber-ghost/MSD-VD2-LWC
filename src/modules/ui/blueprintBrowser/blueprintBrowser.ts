import { LightningElement } from 'lwc';
import { BLUEPRINTS, SLDS_VERSION } from 'data/blueprints';

interface Blueprint {
    name: string;
    root: string | null;
    tag: string;
    classes: string[];
    borrowed: string[];
    hooks: string[];
    privateHooks: string[];
    usedIn: string[];
    missing: string[];
    bundled: boolean;
    deprecated: boolean;
    bytes: number;
}

const ALL = BLUEPRINTS as Blueprint[];

/**
 * Browses the SLDS 2 blueprints that are installed.
 *
 * The blueprints are tier 2 of the lego: the classes you write by hand for a
 * structure no `lightning-*` component covers. They are also the easiest thing
 * on the site to get wrong, because SLDS 2 dropped classes SLDS 1 had and a
 * class that does not exist fails silently -- the markup renders, unstyled.
 *
 * So this answers the three questions the rules make you ask before writing
 * one: does the class ship in THIS build, is there a component that would have
 * saved you the markup, and what may be restyled on it.
 *
 * Generated by `npm run blueprints` from `dist/components/*`, never
 * hand-maintained -- see `scripts/build-blueprints.mjs`.
 */
export default class BlueprintBrowser extends LightningElement {
    static renderMode: 'light' | 'shadow' = 'light';

    version = SLDS_VERSION;
    query = '';
    usedOnly = false;
    selected = ALL[0]?.name ?? '';

    get summary(): string {
        const used = ALL.filter((b) => b.usedIn.length).length;
        const tagged = ALL.filter((b) => b.tag).length;
        return (
            `${ALL.length} blueprints in SLDS ${this.version}. ` +
            `${tagged} have a lightning-* tag of the same name. ` +
            `${used} are used on this site.`
        );
    }

    get matches(): Blueprint[] {
        const term = this.query.trim().toLowerCase();
        return ALL.filter((b) => {
            if (this.usedOnly && !b.usedIn.length) return false;
            if (!term) return true;
            // Match the class names too: "what ships the class I half-remember"
            // is the question this page gets asked most.
            return (
                b.name.toLowerCase().includes(term) ||
                b.classes.some((c) => c.includes(term))
            );
        });
    }

    get navItems(): { name: string; label: string; count: number }[] {
        return this.matches.map((b) => ({
            name: b.name,
            label: b.name,
            count: b.classes.length
        }));
    }

    get matchCount(): string {
        const n = this.matches.length;
        return n === ALL.length ? `${n} blueprints` : `${n} of ${ALL.length}`;
    }

    /** The selection can be filtered away; fall back rather than blank out. */
    get current(): Blueprint {
        return (
            this.matches.find((b) => b.name === this.selected) ??
            this.matches[0] ??
            ALL[0]
        );
    }

    get selectedName(): string {
        return this.current?.name ?? '';
    }

    get ownClasses(): { key: string; name: string }[] {
        return this.current.classes.map((c) => ({ key: c, name: c }));
    }

    get borrowedClasses(): { key: string; name: string }[] {
        return this.current.borrowed.map((c) => ({ key: c, name: c }));
    }

    get hookList(): { key: string; name: string }[] {
        return this.current.hooks.map((h) => ({ key: h, name: h }));
    }

    get privateList(): { key: string; name: string }[] {
        return this.current.privateHooks.map((h) => ({ key: h, name: h }));
    }

    get usedList(): { key: string; name: string }[] {
        return this.current.usedIn.map((f) => ({ key: f, name: f }));
    }

    get missingList(): { key: string; name: string }[] {
        return this.current.missing.map((c) => ({ key: c, name: c }));
    }

    get hasBorrowed(): boolean {
        return this.current.borrowed.length > 0;
    }

    get hasHooks(): boolean {
        return this.current.hooks.length > 0;
    }

    get hasPrivate(): boolean {
        return this.current.privateHooks.length > 0;
    }

    get isUsed(): boolean {
        return this.current.usedIn.length > 0;
    }

    get hasMissing(): boolean {
        return this.current.missing.length > 0;
    }

    get tagLabel(): string {
        return this.current.tag || 'No tag of this name — write the blueprint markup';
    }

    get sizeLabel(): string {
        return `${Math.round(this.current.bytes / 1024)} KB of CSS`;
    }

    handleSearch(event: Event): void {
        this.query = (event.target as HTMLInputElement).value ?? '';
    }

    handleUsedOnly(event: Event): void {
        this.usedOnly = (event.target as HTMLInputElement).checked;
    }

    handleSelect(event: CustomEvent): void {
        this.selected = (event.detail as { name: string }).name;
    }
}
