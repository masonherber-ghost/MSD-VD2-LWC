import { LightningElement } from 'lwc';
import { COMPOSITIONS, SEP_CLASSES } from 'data/compositions';

interface CssFacts {
    lines: number;
    text: string;
    selectors: string[];
    hooks: string[];
    tokens: string[];
    siteTokens: string[];
    parts: string[];
    privateHooks: string[];
    rawColors: string[];
    important: number;
}

interface Composition {
    name: string;
    tag: string;
    doc: string;
    composes: string[];
    wraps: string[];
    blueprints: string[];
    sepClasses: string[];
    hasCss: boolean;
    css: CssFacts | null;
    htmlLines: number;
}

interface SepClass {
    name: string;
    note: string;
    rules: { selector: string; body: string }[];
    usedIn: string[];
}

const ALL = COMPOSITIONS as Composition[];
const SEP = SEP_CLASSES as SepClass[];

const list = (values: string[], prefix: string) =>
    values.map((v, i) => ({ key: `${prefix}-${i}-${v}`, name: v }));

/**
 * Browses the composition wrappers this project wrote, and what each one costs.
 *
 * A wrapper in `src/modules/ui/` is composition, not a new control -- shipped
 * components and blueprint markup, assembled. The rules allow it without the
 * custom component gate. What they do NOT allow is quietly bending a shipped
 * component to match a picture, and the difference between the two is invisible
 * in a screenshot: it lives in the stylesheet.
 *
 * So this is ordered by CSS written, heaviest first, and every wrapper reports
 * what its CSS actually touches -- published hooks and tokens (sanctioned),
 * `::part()` (sanctioned but the most upgrade-sensitive thing on the list),
 * private `--_slds-*` hooks (off limits) and raw colour values (will not follow
 * a theme). A wrapper with no stylesheet is the ideal, and several are.
 *
 * Generated by `npm run compositions` from our own source, with each wrapper's
 * prose read out of its own leading docblock so the two cannot disagree.
 */
export default class CompositionBrowser extends LightningElement {
    static renderMode: 'light' | 'shadow' = 'light';

    query = '';

    get summary(): string {
        const styled = ALL.filter((c) => c.hasCss).length;
        const lines = ALL.reduce((n, c) => n + (c.css?.lines ?? 0), 0);
        return (
            `${ALL.length} wrappers. ${ALL.length - styled} need no stylesheet at all; ` +
            `the other ${styled} come to ${lines} lines of CSS between them.`
        );
    }

    get rows() {
        const term = this.query.trim().toLowerCase();
        return ALL.filter(
            (c) =>
                !term ||
                c.name.toLowerCase().includes(term) ||
                c.tag.includes(term) ||
                c.composes.some((t) => t.includes(term))
        )
            // Heaviest first: the point of the page is what the wrappers cost,
            // and a 218-line stylesheet is the finding, not the 6-line one.
            .slice()
            .sort((a, b) => (b.css?.lines ?? 0) - (a.css?.lines ?? 0))
            .map((c) => {
                const css = c.css;
                return {
                    ...c,
                    key: c.name,
                    cssLabel: css ? `${css.lines} lines of CSS` : 'No stylesheet',
                    cssIcon: css ? 'utility:info' : 'utility:success',
                    composesList: list(c.composes, c.name),
                    wrapsList: list(c.wraps, c.name),
                    blueprintList: list(c.blueprints, c.name),
                    sepList: list(c.sepClasses, c.name),
                    hasComposes: c.composes.length > 0,
                    hasWraps: c.wraps.length > 0,
                    hasBlueprints: c.blueprints.length > 0,
                    hasSep: c.sepClasses.length > 0,
                    hooksList: list(css?.hooks ?? [], c.name),
                    tokensList: list(css?.tokens ?? [], c.name),
                    siteTokensList: list(css?.siteTokens ?? [], c.name),
                    partsList: list(css?.parts ?? [], c.name),
                    privateList: list(css?.privateHooks ?? [], c.name),
                    rawList: list(css?.rawColors ?? [], c.name),
                    hasHooks: (css?.hooks.length ?? 0) > 0,
                    hasTokens: (css?.tokens.length ?? 0) + (css?.siteTokens.length ?? 0) > 0,
                    hasParts: (css?.parts.length ?? 0) > 0,
                    hasPrivate: (css?.privateHooks.length ?? 0) > 0,
                    hasRaw: (css?.rawColors.length ?? 0) > 0,
                    hasImportant: (css?.important ?? 0) > 0,
                    importantLabel: `${css?.important ?? 0} × !important`,
                    cssText: css?.text ?? ''
                };
            });
    }

    get sepRows() {
        return SEP.map((s) => ({
            ...s,
            key: s.name,
            usedLabel:
                s.usedIn.length === 1
                    ? 'Used on 1 screen'
                    : `Used on ${s.usedIn.length} screens`,
            ruleRows: s.rules.map((r, i) => ({
                key: `${s.name}-${i}`,
                selector: r.selector,
                body: r.body
            })),
            usedList: list(s.usedIn, s.name)
        }));
    }

    handleSearch(event: Event): void {
        this.query = (event.target as HTMLInputElement).value ?? '';
    }
}
