/**
 * Generates src/modules/data/tokens/tokens.js from the INSTALLED SLDS
 * stylesheet plus this project's own design-tokens.css.
 *
 * Nothing here is hand-maintained. SLDS 2 ships hundreds of tokens and they
 * move with the package version, so the only list that stays true is one read
 * off the stylesheet that is actually installed. Re-run after upgrading
 * @salesforce-ux/design-system-2:
 *
 *   npm run tokens
 *
 * Private hooks (--_slds-*) are collected too, but only so the browser can show
 * what is OFF LIMITS by name. They are never presented as usable.
 */

import fs from 'node:fs';
import path from 'node:path';

const SLDS_CSS = path.resolve(
    'node_modules/@salesforce-ux/design-system-2/dist/css/bundled/slds2.cosmos.css'
);
const PROJECT_CSS = path.resolve('src/assets/css/design-tokens.css');
const OUT = path.resolve('src/modules/data/tokens/tokens.js');

const css = fs.readFileSync(SLDS_CSS, 'utf8');

/** Every `--name: value;` declaration, last one wins (later rules override). */
function declarations(source, prefix) {
    const re = new RegExp(`(${prefix}[a-z0-9-]+)\\s*:\\s*([^;}]+)[;}]`, 'g');
    const found = new Map();
    for (const m of source.matchAll(re)) {
        found.set(m[1], m[2].trim());
    }
    return found;
}

const globals = declarations(css, '--slds-g-');

/**
 * Private hooks are counted by NAME, not by declaration: several are only ever
 * referenced, and a consumer needs to recognise all of them as off limits.
 */
const privateNameSet = new Set([...css.matchAll(/--_slds-[a-z0-9-]+/g)].map((m) => m[0]));

/** Component hooks are referenced far more often than declared, so collect names. */
const hookNames = new Set(
    [...css.matchAll(/--slds-c-[a-z0-9-]+/g)].map((m) => m[0])
);

/** `--slds-g-color-accent-1` -> family `color`. */
function globalFamily(name) {
    return name.replace('--slds-g-', '').split('-')[0];
}

/** `--slds-c-card-body-spacing-block` -> component `card`. */
function hookComponent(name) {
    return name.replace('--slds-c-', '').split('-')[0];
}

/**
 * How the browser should preview a family. `swatch` paints the value, `bar`
 * draws a box that wide, `text` sets font-size, and `value` just prints it.
 */
const PREVIEW = {
    color: 'swatch',
    spacing: 'bar',
    sizing: 'bar',
    radius: 'radius',
    shadow: 'shadow',
    font: 'text',
    duration: 'value',
    ratio: 'value'
};

const globalFamilies = [...new Set([...globals.keys()].map(globalFamily))]
    .sort()
    .map((family) => ({
        family,
        preview: PREVIEW[family] || 'value',
        tokens: [...globals.entries()]
            .filter(([name]) => globalFamily(name) === family)
            .sort(([a], [b]) => a.localeCompare(b, undefined, { numeric: true }))
            .map(([name, value]) => ({ name, value }))
    }));

const componentHooks = [...new Set([...hookNames].map(hookComponent))]
    .sort()
    .map((component) => ({
        component,
        tokens: [...hookNames]
            .filter((n) => hookComponent(n) === component)
            .sort((a, b) => a.localeCompare(b))
            .map((name) => ({ name }))
    }));

/** Ours. Parsed from design-tokens.css so the two can never disagree. */
const projectCss = fs.existsSync(PROJECT_CSS) ? fs.readFileSync(PROJECT_CSS, 'utf8') : '';
const projectTokens = [];
const seenProject = new Set();
for (const m of projectCss.matchAll(/(--site-[a-z0-9-]+)\s*:\s*([^;]+);/g)) {
    const [, name, value] = m;
    if (seenProject.has(name)) {
        // A redefinition inside a media query: record it as a breakpoint step.
        projectTokens.find((t) => t.name === name).steps.push(value.trim());
        continue;
    }
    seenProject.add(name);
    projectTokens.push({ name, value: value.trim(), steps: [] });
}

const privateNames = [...privateNameSet].sort().map((name) => ({ name }));

const banner = `// GENERATED by scripts/build-tokens.mjs - do not edit.
// Source: @salesforce-ux/design-system-2 (slds2.cosmos.css)
//         + src/assets/css/design-tokens.css
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(
    OUT,
    `${banner}
export const GLOBAL_FAMILIES = ${JSON.stringify(globalFamilies, null, 4)};

export const COMPONENT_HOOKS = ${JSON.stringify(componentHooks, null, 4)};

export const PROJECT_TOKENS = ${JSON.stringify(projectTokens, null, 4)};

export const PRIVATE_HOOKS = ${JSON.stringify(privateNames, null, 4)};
`
);

const totalGlobals = globalFamilies.reduce((n, f) => n + f.tokens.length, 0);
const totalHooks = componentHooks.reduce((n, c) => n + c.tokens.length, 0);
console.log(
    `tokens: ${totalGlobals} global in ${globalFamilies.length} families, ` +
        `${totalHooks} component hooks across ${componentHooks.length} components, ` +
        `${projectTokens.length} project, ${privateNames.length} private (off limits)`
);
console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
