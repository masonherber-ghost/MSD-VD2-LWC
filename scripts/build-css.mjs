/**
 * Bundles the site stylesheet: src/assets/css/site/** → src/assets/css/site.css.
 *
 * The global CSS is authored as one file per concern — page chrome, one file
 * per shipped component skin, one per blueprint skin, the utilities — and
 * served as ONE stylesheet, which `main.njk` links. Concatenation rather than
 * `@import` on purpose:
 *
 *   - `@import` fetches serially, one round trip per file;
 *   - `ui/exampleStage` adopts the page's stylesheets into each example's
 *     shadow root as constructed sheets, and `CSSStyleSheet.replace()` ignores
 *     `@import` — the /design-system examples would silently lose every skin.
 *
 * ORDER IS THE CASCADE. Every file is unlayered, so for equal specificity the
 * later file wins:
 *
 *   1. site/base.css             page chrome, element defaults
 *   2. site/components/*.css     one per `lightning-*` tag, alphabetical
 *   3. site/blueprints/*.css     one per SLDS blueprint skin, alphabetical
 *   4. site/utilities.css        `sep-` utilities — last, so they win
 *
 * The output is GENERATED and committed, like the other generated files
 * (catalog, tokens): never edit site.css by hand. It runs before `dev` and
 * `build` (npm pre-scripts), and `npm run dev` re-runs it when a source file
 * changes (scripts/dev-server.ts).
 *
 *   npm run css            write the bundle
 *   npm run css -- --check exit 1 if the bundle is out of date
 */

import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve('src/assets/css/site');
const OUT = path.resolve('src/assets/css/site.css');

const sorted = (dir) =>
    fs.existsSync(path.join(ROOT, dir))
        ? fs
              .readdirSync(path.join(ROOT, dir))
              .filter((f) => f.endsWith('.css'))
              .sort()
              .map((f) => `${dir}/${f}`)
        : [];

export function sources() {
    return ['base.css', ...sorted('components'), ...sorted('blueprints'), 'utilities.css'];
}

export function bundle() {
    const files = sources();
    const header = [
        '/* GENERATED by scripts/build-css.mjs (`npm run css`) — DO NOT EDIT.',
        ' * Edit the sources in src/assets/css/site/ and re-run; `npm run dev` does',
        ' * it on save. Order: base, components/*, blueprints/*, utilities.',
        ' *',
        ...files.map((f) => ` *   ${f}`),
        ' */',
        ''
    ].join('\n');
    const body = files.map((f) => {
        const css = fs.readFileSync(path.join(ROOT, f), 'utf8').trimEnd();
        return `/* ==== ${f} ${'='.repeat(Math.max(4, 70 - f.length))} */\n\n${css}\n`;
    });
    return `${header}\n${body.join('\n')}`;
}

export function writeBundle() {
    const next = bundle();
    const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (next !== prev) fs.writeFileSync(OUT, next);
    return next !== prev;
}

if (import.meta.url === `file://${process.argv[1]}`) {
    if (process.argv.includes('--check')) {
        const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
        if (current !== bundle()) {
            console.error('css: src/assets/css/site.css is out of date — run `npm run css`.');
            process.exit(1);
        }
        console.log('css: site.css is up to date.');
    } else {
        const changed = writeBundle();
        console.log(`css: ${sources().length} files → src/assets/css/site.css${changed ? '' : ' (unchanged)'}`);
    }
}
